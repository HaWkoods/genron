import {validate, affected, changedEntries, available} from "./knowledge-core.mjs";
function runTests(){
 const tests=[];
 const base={schema_version:1,foundation:{status:"adopted",description:"fixture only"},entries:[]};
 const a={id:"K-000001",kind:"definition",title:"A",statement:"fixture",assumptions:[],position:[1,1,1,1],depends_on:[],status:"verified",source:"volumes/test.tex",review:"fixture"};
 const b={...a,id:"K-000002",kind:"theorem",title:"B",position:[1,1,1,2],depends_on:[a.id]};
 const c={...b,id:"K-000003",position:[1,1,1,3],depends_on:[b.id]};
 const block=e=>`% genron:begin ${e.id}\n${e.depends_on.map(d=>`% genron:use ${d}`).join("\n")}\n% genron:end ${e.id}\n`;
 const ledger=(...entries)=>({...base,entries});
 const src=(...entries)=>({"volumes/test.tex":entries.map(block).join("")});
 const check=(name,condition)=>{if(!condition)throw Error("FAIL "+name);tests.push(name)};
 const has=(result,code)=>result.errors.some(x=>x.startsWith(code+":"));
 check("empty ledger",validate({...base,foundation:{status:"undecided",description:"pending"}}).errors.length===0);
 check("valid chain",validate(ledger(a,b,c),src(a,b,c)).errors.length===0);
 check("duplicate ID",has(validate(ledger(a,a),src(a)),"DUPLICATE_ID"));
 check("unknown dependency",has(validate(ledger(b),src(b)),"UNKNOWN_DEPENDENCY"));
 check("unverified dependency",has(validate(ledger({...a,status:"draft"},b),src(a,b)),"UNVERIFIED_DEPENDENCY"));
 check("forward dependency",has(validate(ledger({...a,position:[1,1,1,4]},b),src(a,b)),"FORWARD_DEPENDENCY"));
 const cyclic={...a,depends_on:[b.id]};
 check("cycle",has(validate(ledger(cyclic,b),src(cyclic,b)),"CYCLE"));
 check("self cycle",has(validate(ledger({...a,depends_on:[a.id]}),src({...a,depends_on:[a.id]})),"CYCLE"));
 check("unknown manuscript reference",has(validate(ledger(a),{"volumes/test.tex":block(a).replace("% genron:end","\\GenronRef{K-999999}\n% genron:end")}),"UNKNOWN_SOURCE_REFERENCE"));
 check("undeclared manuscript dependency",has(validate(ledger(a,b),src(a,{...b,depends_on:[]}).constructor===Object?{"volumes/test.tex":block(a)+block(b).replace("% genron:use K-000001","% genron:use K-999999")}:{}),"UNDECLARED_SOURCE_DEPENDENCY"));
 check("missing manuscript annotation",has(validate(ledger(a,b),src(a,{...b,depends_on:[]})),"UNMARKED_DEPENDENCY"));
 check("unregistered block",has(validate(ledger(a),src(a,b)),"UNREGISTERED_BLOCK"));
 check("source order",has(validate(ledger(a,b),src(b,a)),"SOURCE_ORDER"));
 check("duplicate position",has(validate(ledger(a,{...b,position:a.position}),src(a,b)),"DUPLICATE_POSITION"));
 check("missing review",has(validate(ledger({...a,review:""}),src(a)),"MISSING_REVIEW"));
 check("unadopted foundation",has(validate({...ledger(a),foundation:{status:"undecided",description:"pending"}},src(a)),"FOUNDATION_UNADOPTED"));
 check("retired dependency",has(validate(ledger({...a,status:"retired"},b),src(b)),"RETIRED_DEPENDENCY"));
 check("draft future references warning",validate(ledger({...a,status:"planned",source:null},{...b,status:"draft"}),src(b)).warnings.some(x=>x.startsWith("UNVERIFIED_DEPENDENCY:")));
 check("reverse transitive impact",affected([ledger(a,b,c)],[a.id]).affected.join(",")===[b.id,c.id].join(","));
 check("deleted old edge impact",affected([ledger(a,b,c),ledger(a,{...b,depends_on:[]},c)],[a.id]).affected.length===2);
 check("statement change",changedEntries(ledger(a,b),ledger({...a,statement:"changed"},b)).join(",")===a.id);
 check("manuscript change",changedEntries(ledger(a,b),ledger(a,b),src(a,b),{"volumes/test.tex":block(a)+block(b)+"changed"}).length===2);
 check("available strictly before position",available(ledger(a,b,c),b.position).map(e=>e.id).join(",")===a.id);
 return tests;
}
for(const name of runTests()) console.log("PASS "+name);
